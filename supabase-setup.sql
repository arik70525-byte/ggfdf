-- Публичное чтение проектов; создание и удаление — только для arik70525@gmail.com.

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  name text not null,
  description text default '',
  storage_path text not null unique,
  public_url text not null,
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);

alter table public.projects enable row level security;
grant select on public.projects to anon, authenticated;
grant insert, delete on public.projects to authenticated;
grant usage, select on sequence public.projects_id_seq to authenticated;

drop policy if exists "Anyone can view projects" on public.projects;
create policy "Anyone can view projects" on public.projects
for select to anon, authenticated using (true);

drop policy if exists "Only site admin can add projects" on public.projects;
create policy "Only site admin can add projects" on public.projects
for insert to authenticated
with check (
  (auth.jwt() ->> 'email') = 'arik70525@gmail.com'
  and created_by = auth.uid()
);

drop policy if exists "Only site admin can delete projects" on public.projects;
create policy "Only site admin can delete projects" on public.projects
for delete to authenticated
using ((auth.jwt() ->> 'email') = 'arik70525@gmail.com');

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('projects', 'projects', true, 2097152, array['text/html','text/plain'])
on conflict (id) do update set public = true, file_size_limit = 2097152, allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Public can view project files" on storage.objects;
create policy "Public can view project files" on storage.objects
for select to anon, authenticated
using (bucket_id = 'projects');

drop policy if exists "Only site admin can upload project files" on storage.objects;
create policy "Only site admin can upload project files" on storage.objects
for insert to authenticated
with check (
  bucket_id = 'projects'
  and (auth.jwt() ->> 'email') = 'arik70525@gmail.com'
);

drop policy if exists "Only site admin can delete project files" on storage.objects;
create policy "Only site admin can delete project files" on storage.objects
for delete to authenticated
using (
  bucket_id = 'projects'
  and (auth.jwt() ->> 'email') = 'arik70525@gmail.com'
);
